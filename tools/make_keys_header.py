#!/usr/bin/env python3
"""Write src/controller/common/keys.h: the two public keys the bootloader checks
Signature A and Signature B against (Interfaces Sec. 5.5).

Reads the key pairs made by make_dev_keys.py, which live outside the repository,
and copies only their 32-byte public halves into the header.

Usage: make_keys_header.py <key-a.pem> <key-b.pem> <output keys.h>
"""
import hashlib
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization

PUBLIC_KEY_BYTES = 32  # Ed25519 public key length [RFC 8032, Sec. 5.1.5]
BYTES_PER_LINE = 8


def public_key(pem_path: Path) -> bytes:
    private = serialization.load_pem_private_key(pem_path.read_bytes(), password=None)
    raw = private.public_key().public_bytes(
        encoding=serialization.Encoding.Raw, format=serialization.PublicFormat.Raw
    )
    assert len(raw) == PUBLIC_KEY_BYTES
    return raw


def c_array(name: str, key: bytes) -> str:
    lines = []
    for i in range(0, len(key), BYTES_PER_LINE):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in key[i:i + BYTES_PER_LINE]) + ",")
    return f"static const uint8_t {name}[{PUBLIC_KEY_BYTES}] = {{\n" + "\n".join(lines) + "\n};\n"


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    key_a, key_b = public_key(Path(sys.argv[1])), public_key(Path(sys.argv[2]))
    header = f"""/*
 * keys.h — GENERATED by tools/make_keys_header.py; do not edit by hand.
 *
 * The public keys for Signature A and Signature B (Interfaces Sec. 5.5). They come from the
 * DEVELOPMENT key pairs {Path(sys.argv[1]).name} and {Path(sys.argv[2]).name}, made by
 * tools/make_dev_keys.py and kept in keys-dev/ next to the repository, outside it.
 * Only these public halves are in the repository. Bench keys: never for flight.
 *
 * SHA-256 of key A: {hashlib.sha256(key_a).hexdigest()}
 * SHA-256 of key B: {hashlib.sha256(key_b).hexdigest()}
 */
#ifndef KEYS_H
#define KEYS_H

#include <stdint.h>

{c_array("PUBLIC_KEY_A", key_a)}
{c_array("PUBLIC_KEY_B", key_b)}
#endif /* KEYS_H */
"""
    Path(sys.argv[3]).write_text(header)
    print(f"wrote {sys.argv[3]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
